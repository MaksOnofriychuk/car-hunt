/** Нижній регістр, ʼ→', подвійні пробіли геть. Ключі словників у цій формі. */
export function normalizeWord(value: string): string {
  return value
    .toLowerCase()
    .replace(/[’'`ʼ]/g, 'ʼ')
    .replace(/\s+/g, ' ')
    .trim()
}
